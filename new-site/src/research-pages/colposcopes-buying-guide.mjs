      "An angled head changes more than posture",
      "The manufacturer identifies 45-degree angled oculars on the 1DW LED, but also states that this version has no green filter. Do not assume it is simply a 1D LED with a more comfortable viewing angle. Let the clinician decide whether that configuration fits the required examination. Make the same distinction when comparing documented photo/video models. Leisegang describes the 3ML LED for use with an external camera; the angled 3MLW LED also lacks the green filter. A family name or seller photograph can hide these differences, so put the exact model and required functions on the acceptance record. A used optical instrument should be assessed for its actual optical, illumination, mechanical and electrical condition by appropriately qualified personnel. Compare a supported repair with replacement when the present instrument still meets the clinical brief. Do not treat age or a new LED label as a measured reliability ranking."
