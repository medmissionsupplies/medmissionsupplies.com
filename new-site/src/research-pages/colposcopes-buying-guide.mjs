      "Separate the optical decision from the recording decision",
      "A clinician may need an appropriate illuminated binocular view without a connected recording workstation. Another service may need retained images, teaching material or transfer into a patient record. Write those requirements separately. Buying a camera-equipped instrument without the required reporting route can cost more while leaving the documentation problem unresolved. Leisegang’s standard-model page gives a useful optical comparison: the 1E LED has fixed 15× magnification, while the 1D LED offers 7.5×, 15× and 30×. The deciding question is whether the clinician needs those selectable views for the intended service, not whether the larger specification list looks better. Have the intended users evaluate the optical view, focusing, reach and working posture with the actual patient chair and room arrangement. This is equipment selection, not a claim that a particular magnification improves diagnostic accuracy or replaces training."
