      "A listing headed “EMG” is not enough to specify an intraoperative nerve-monitoring service. The surgical and monitoring leads must define the intended work, required channels, patient interfaces and responsibility for interpreting the information. A console cannot substitute for that expertise or for the agreed clinical workflow. Medtronic’s December 2022 regional description distinguishes NIM-Response 3.0, monitoring up to four nerve-muscle channels, from NIM-Neuro 3.0, up to eight. It also identifies APS electrode-dependent continuous monitoring. More channels or a named feature is useful only when the planned procedure and complete approved setup require it."
