      "Check software and disposable notices separately",
      "NIM Vital is a separate product from NIM 3.0, and its correction history illustrates why “software updated” needs a version and date. FDA’s 2024 false-negative-response notice described a correction to version 1.5.4. A later recall record, posted April 18, 2025, identifies increased stimulus artifact in Vital systems with version 1.6.4 or earlier and describes a manufacturer update to 1.7.5. That later record was still shown as open when checked on October 18, 2026. Obtain applicable manufacturer correction evidence for the exact offered system; do not treat an earlier upgrade as blanket clearance or apply a Vital notice indiscriminately to a NIM 3.0 console. Accessories need their own review. FDA’s July 2024 letter, updated that November, directs users not to use NIM Standard and Contact EMG endotracheal tubes and describes removal of all affected tubes from inventory because of blockage concerns. A package of recalled tubes has no usable value merely because it is unopened. Check exact identifiers and any proposed alternative through the responsible clinical and technical team."
