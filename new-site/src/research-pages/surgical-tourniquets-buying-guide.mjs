      "Price the cuff inventory that the chosen system requires",
      "For the A.T.S. 5000, Zimmer describes separate ports for inflation/deflation and pressure monitoring. Its EZ LOP feature also depends on identified compatible cuffs. These are reasons to reconcile the proposed cuff stock and functions against the exact system, rather than assume all cuffs with a familiar connector supply the same workflow. The 2022 ordering table distinguishes 60500010100, the A.T.S. 5000TS with hoses, from 60500010200, with cuffs and hoses. That small package-code difference changes the starting inventory. For a used offer, count the actual supplied parts and condition; an old catalogue code does not establish that its original contents remain in the box. Build the initial stock around the approved sizes and types the service needs. Compare replenishment quantities, sleeves, hoses and necessary spares. A supplied assortment may have little value if it misses a routinely needed size or consists of components that the hospital cannot continue sourcing."
