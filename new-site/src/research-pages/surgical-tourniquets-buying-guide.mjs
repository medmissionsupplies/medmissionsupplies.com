      "Ask the surgical team to specify the intended work, independently controlled cuff requirement and patient-size range before selecting a console. Then identify the cuff and hose system that supplies that capability. A product described as single-port should not automatically be treated as a single-cuff system. Zimmer’s March 2022 brochure makes the distinction concrete: A.T.S. 5000 is dual-port and A.T.S. 2200 single-port, but both are listed as dual-cuff systems. Its current product page names A.T.S. 5000 and the single-port A.T.S. 3200. Do not silently substitute the newer model name into an older comparison table; match the offered model and its current instructions."
