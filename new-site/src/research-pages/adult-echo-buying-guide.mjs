      "Do not buy the analysis twice—or assume it is included",
      "Separate acquisition on the scanner from analysis on a workstation and final reporting. Establish where each required measurement is made, whether it remains editable after export and which licences the hospital receives. An attractive analysis demonstration may use software that is absent from the delivered console or belongs to another workstation. For a service that only needs its agreed routine package now, advanced analysis belongs on a separately priced line with a named use. If it is essential to the planned service, it belongs in the acceptance demonstration. Either answer is more useful than buying a premium label and discovering later that the necessary option still costs extra."
