      "Separate the scanner's age from the tube's history",
      "A used CT offer contains several histories. The gantry may be older than its current tube; the tube may have been changed after a fault; a controller or software upgrade may have changed which records are readily available. A manufacturing year and one screenshot cannot explain all of that. Ask for the installed tube's model, serial number, installation date and replacement invoice or service record. Reconcile those documents with a recent, dated counter capture and maintenance history. Identify whether a displayed total belongs to the installed tube, the scanner or another component. Any unexplained mismatch belongs in the technical review before the buyer treats a low count as an economic advantage."
