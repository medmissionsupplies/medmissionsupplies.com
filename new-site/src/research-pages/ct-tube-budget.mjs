      "Price three ways to own the same scanner",
      "Request comparable offers retaining the installed tube, supplying an identified replacement, and adding explicitly tube-inclusive service. For each, state the replacement category, warranty start, freight, labor, calibration and acceptance obligations. A new tube, a refurbished tube and a used tube are different offers even when all fit the same scanner. GE's published tube and parts pages illustrate why terminology matters: warranty provisions distinguish tube families and component condition. The D3889T terms cited here exclude installation and equipment use outside the United States. A mission hospital abroad cannot treat that US warranty as its support plan. Obtain the terms attached to the actual destination quotation, including diagnosis, engineer travel, installation and covered causes of failure. Compare the complete remedy available at the hospital."
