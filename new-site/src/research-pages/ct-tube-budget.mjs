      "Use exposure records without turning them into a countdown",
      "Scan seconds, exposure counts and accumulated mAs describe different quantities. Record the measure and its definition rather than comparing unlabeled numbers across brands. Ask the engineer how the system records usage and whether the available record spans the installed tube's entire service. Include fault reports and corrective work alongside the number. Block Imaging publishes experience-based lifespan and price discussions for MRC tubes. These are useful prompts for questions, but they are seller observations, not an individual tube guarantee. Subtracting a used tube's count from an advertised lifespan range creates an appearance of precision that the evidence cannot support. The remaining uncertainty needs a funded response."
